#!/usr/bin/env node
// Build supabase/seed/20_definitions.sql from supabase/seed/definitions/*.json (T1-11).
//   * every definition is parsed and statically analysed by the TS engine (the same analyser admins publish with);
//   * definition_hash = sha256(JCS(definition)) computed by the engine — never by hand;
//   * the global remote-config layer v1 is the engine's typed defaults (schema/config), validated;
//   * output is idempotent SQL (families, version 1, activation for everyone).
// Usage (Deno runs the engine's TypeScript directly):
//   deno run --allow-read --allow-write --config packages/fess_pos_engine_ts/deno.json tools/seed/build-definitions.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const engine = await import(join(root, 'packages/fess_pos_engine_ts/src/index.ts'));

const REASON_CATEGORIES = ['assignment_reject', 'unable_to_complete', 'cancel', 'geofence_override', 'review_return',
  'review_reject', 'appointment_not_secured', 'reassign', 'unschedule', 'envelope_resolution'];
const DECLARATIONS = ['agent_declaration', 'merchant_certification'];

const dir = join(root, 'supabase/seed/definitions');
const defs = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const parsed = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  for (const def of Array.isArray(parsed) ? parsed : [parsed]) defs.push({ file, def });
}

const bundle = { forms: {}, flows: {}, views: {}, lookup_lists: [], reason_code_categories: REASON_CATEGORIES, declarations: DECLARATIONS };
for (const { def } of defs) {
  if (def.kind === 'form') bundle.forms[def.family] = def;
  if (def.kind === 'flow') bundle.flows[def.family] = def;
  if (def.kind === 'view') bundle.views[def.family] = def;
}

const sqlText = (s) => `$d$${s}$d$`;
const out = [
  '-- GENERATED by tools/seed/build-definitions.mjs from supabase/seed/definitions/*.json — do not edit by hand.',
  '-- Global default definitions v1 (all kinds) + activation for everyone, and the global remote-config layer v1.',
  '-- Idempotent. Published versions are immutable: a change is a new version published in the admin panel.',
  '',
];

let failed = false;
for (const { file, def } of defs) {
  const res = engine.analyseDefinition(def, bundle);
  for (const w of res.warnings) console.warn(`  warn  ${def.kind}/${def.family} ${w.code} ${w.path}: ${w.message}`);
  if (!res.ok) {
    failed = true;
    for (const e of res.errors) console.error(`  ERROR ${file} ${def.kind}/${def.family} ${e.code} ${e.path}: ${e.message}`);
    continue;
  }
  const hash = await engine.definitionHash(def);
  const requires = res.requires ?? engine.computeRequires(def);
  console.log(`  ok    ${def.kind}/${def.family} v${def.version}  ${hash.slice(0, 12)}…`);
  const title = def.title ?? def.family;
  out.push(
    `-- ${def.kind}/${def.family} v${def.version}`,
    `insert into pos.definition_families (kind, key, scope, title) values ('${def.kind}', '${def.family}', 'global', ${sqlText(title)})`,
    `on conflict (kind, key, bank_id) do nothing;`,
    `insert into pos.definition_versions (family_id, version, spec_version, definition, definition_hash, requires, changelog)`,
    `select f.id, ${def.version}, '${def.spec_version}', ${sqlText(JSON.stringify(def))}::jsonb, '${hash}', ${sqlText(JSON.stringify(requires))}::jsonb,`,
    `       '{"summary": "Initial global default"}'::jsonb`,
    `  from pos.definition_families f where f.kind = '${def.kind}' and f.key = '${def.family}' and f.bank_id is null`,
    `on conflict (family_id, version) do nothing;`,
    `insert into pos.definition_activations (family_id, version_id, audience, reason)`,
    `select v.family_id, v.id, '{"type": "all"}'::jsonb, 'Initial global default'`,
    `  from pos.definition_versions v join pos.definition_families f on f.id = v.family_id`,
    ` where f.kind = '${def.kind}' and f.key = '${def.family}' and f.bank_id is null and v.version = ${def.version}`,
    `   and not exists (select 1 from pos.definition_activations a where a.version_id = v.id);`,
    '',
  );
}

// Remote config: global layer v1 = the engine's typed defaults (schema/config/defaults.json), validated.
const defaults = engine.remoteConfigDefaults();
const check = engine.resolveRemoteConfig([defaults]);
if (!check.ok) {
  failed = true;
  for (const e of check.errors) console.error(`  ERROR remote config ${e.path}: ${e.message}`);
}
out.push(
  '-- remote config: global layer v1 (engine defaults, schema/config)',
  `insert into pos.remote_config_versions (layer, subject_id, version, values, schema_version, reason)`,
  `select 'global', null, 1, ${sqlText(JSON.stringify(defaults))}::jsonb, '1.0', 'Initial defaults (schema/config/defaults.json)'`,
  ` where not exists (select 1 from pos.remote_config_versions where layer = 'global');`,
  '',
);

if (failed) {
  console.error('\nDefinitions failed analysis — 20_definitions.sql not written.');
  process.exit(1);
}
writeFileSync(join(root, 'supabase/seed/20_definitions.sql'), out.join('\n'));
console.log(`\nwrote supabase/seed/20_definitions.sql (${defs.length} definitions + remote config)`);
